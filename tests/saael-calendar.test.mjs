import assert from 'node:assert/strict';
import { availableTimes, isValidDate, zonedNow, formatServicePrice, validateScheduling } from '../storefront/brands/saael/calendar-data.js';
import { resolveSaaelContent } from '../storefront/brands/saael/content.js';
const first={id:'first',title:'First service',description:'',details:'',sample:false,price:1500,durationMinutes:60};
const second={id:'second',title:'Second service',description:'',details:'',sample:false,price:2500,durationMinutes:90};
const content=resolveSaaelContent({currency:'KGS',services:[first,second],availability:[{date:'2026-10-12',start:'09:00',end:'12:00',serviceId:''},{date:'2026-10-13',start:'14:00',end:'16:00',serviceId:'second'}]});
const now=new Date('2026-10-09T12:00:00Z');
assert.deepEqual(validateScheduling(content),[]);
assert.deepEqual(availableTimes(content,first,'2026-10-12',now),['09:00','10:00','11:00']);
assert.deepEqual(availableTimes(content,second,'2026-10-12',now),['09:00','10:30']);
assert.deepEqual(availableTimes(content,first,'2026-10-13',now),[]);
assert.deepEqual(availableTimes(content,second,'2026-10-13',now),['14:00']);
assert.deepEqual(availableTimes(content,first,'2026-10-12',new Date('2026-10-12T04:00:00Z')),['11:00']);
assert.deepEqual(availableTimes(content,first,'2026-10-12',new Date('2026-10-13T00:00:00Z')),[]);
assert.deepEqual(availableTimes({...content,availability:[]},first,'2026-10-12',now),[]);
assert.deepEqual(availableTimes(content,{...first,durationMinutes:null},'2026-10-12',now),[]);
assert.equal(isValidDate('2027-02-29'),false);assert.equal(isValidDate('2028-02-29'),true);
assert.deepEqual(zonedNow('Asia/Bishkek',new Date('2026-10-09T23:00:00Z')),{date:'2026-10-10',time:'05:00'});
assert.equal(formatServicePrice({...first,price:null},'KGS'),'Price to be confirmed');
assert.match(formatServicePrice({...first,price:0},'KGS'),/0/);
assert.notEqual(formatServicePrice(first,'KGS'),formatServicePrice(second,'KGS'));
assert.ok(validateScheduling({...content,currency:''}).length);
assert.ok(validateScheduling({...content,timeZone:'Invalid/Zone'}).length);
assert.ok(validateScheduling({...content,services:[{...first,price:-1}]}).length);
assert.ok(validateScheduling({...content,services:[{...first,durationMinutes:0}]}).length);
assert.ok(validateScheduling({...content,availability:[{date:'2026-10-12',start:'16:00',end:'14:00',serviceId:''}]}).length);
assert.ok(validateScheduling({...content,availability:[{date:'2026-10-12',start:'14:00',end:'16:00',serviceId:'missing'}]}).length);
assert.deepEqual(resolveSaaelContent({services:[{id:'legacy'}]}).services[0],{price:null,durationMinutes:null,id:'legacy'});
console.log('Calendar checks passed: service-specific duration/prices, fitting slots, past-time filtering, date validity, time zone, empty availability and invalid settings.');
